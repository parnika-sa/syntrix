import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import * as topojson from "topojson-client";
import * as d3Geo from "d3-geo";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// 1. Read topojson from world-atlas
const worldAtlasPath = path.resolve(__dirname, "../node_modules/world-atlas/land-110m.json");
const worldTopology = JSON.parse(fs.readFileSync(worldAtlasPath, "utf-8"));

// 2. Extract land GeoJSON feature
const landFeature = topojson.feature(worldTopology, worldTopology.objects.land);

// 3. Set up Natural Earth 1 projection with 1000x500 viewBox
const width = 1000;
const height = 500;

const projection = d3Geo
  .geoNaturalEarth1()
  .fitExtent(
    [
      [20, 20],
      [width - 20, height - 20],
    ],
    landFeature
  );

// 4. Sample land on a regular ~2 degree grid
const dots = [];
const step = 2.0; // 2 degree spacing

for (let lat = -58; lat <= 80; lat += step) {
  for (let lon = -180; lon <= 180; lon += step) {
    if (d3Geo.geoContains(landFeature, [lon, lat])) {
      const projected = projection([lon, lat]);
      if (projected) {
        const x = Math.round(projected[0] * 10) / 10;
        const y = Math.round(projected[1] * 10) / 10;
        dots.push(`M${x} ${y}h0`);
      }
    }
  }
}

const worldDotsPath = dots.join("");
console.log(`Generated ${dots.length} land dots. Path string length: ${worldDotsPath.length}`);

// 5. Project city coordinates:
// Ludhiana (30.90N, 75.85E) plus San Francisco, New York, London, Dubai, Singapore, Sydney
const rawCities = [
  { id: "ludhiana", name: "Ludhiana HQ", region: "Punjab, India", lon: 75.8573, lat: 30.9010, isHQ: true },
  { id: "sf", name: "San Francisco", region: "USA (West)", lon: -122.4194, lat: 37.7749 },
  { id: "nyc", name: "New York", region: "USA (East)", lon: -74.0060, lat: 40.7128 },
  { id: "london", name: "London", region: "UK & Western Europe", lon: -0.1278, lat: 51.5074 },
  { id: "dubai", name: "Dubai", region: "UAE & Middle East", lon: 55.2708, lat: 25.2048 },
  { id: "singapore", name: "Singapore", region: "Southeast Asia", lon: 103.8198, lat: 1.3521 },
  { id: "sydney", name: "Sydney", region: "Australia", lon: 151.2093, lat: -33.8688 },
];

const projectedCities = rawCities.map((city) => {
  const [x, y] = projection([city.lon, city.lat]);
  return {
    ...city,
    x: Math.round(x * 10) / 10,
    y: Math.round(y * 10) / 10,
  };
});

console.log("Projected cities:", projectedCities);

const hub = projectedCities.find((c) => c.isHQ);

// 6. Generate smooth curved quadratic bezier arcs from Ludhiana to each remote hub
const arcs = projectedCities
  .filter((c) => !c.isHQ)
  .map((city, idx) => {
    // Control point with arc curvature
    const midX = (hub.x + city.x) / 2;
    const midY = (hub.y + city.y) / 2;
    const dx = city.x - hub.x;
    const dy = city.y - hub.y;
    const dist = Math.sqrt(dx * dx + dy * dy);

    // Curve upwards (arch)
    const curvature = Math.min(dist * 0.28, 80);
    const cpX = Math.round((midX - dy * 0.08) * 10) / 10;
    const cpY = Math.round((midY - curvature) * 10) / 10;

    const d = `M ${hub.x} ${hub.y} Q ${cpX} ${cpY} ${city.x} ${city.y}`;
    return {
      toId: city.id,
      cityName: city.name,
      d,
      delay: (idx * 0.3).toFixed(1) + "s",
    };
  });

// 7. Write to src/data/worldDots.ts
const outputContent = `// Automatically generated by scripts/generate-world-dots.mjs - DO NOT EDIT MANUALLY
export interface WorldCity {
  id: string;
  name: string;
  region: string;
  lon?: number;
  lat?: number;
  x: number;
  y: number;
  isHQ?: boolean;
}

export interface DeliveryArc {
  toId: string;
  cityName: string;
  d: string;
  delay: string;
}

export const worldViewBox = {
  width: ${width},
  height: ${height},
};

export const projectedCities: WorldCity[] = ${JSON.stringify(projectedCities, null, 2)};

export const deliveryArcs: DeliveryArc[] = ${JSON.stringify(arcs, null, 2)};

export const worldDotsPath = "${worldDotsPath}";
`;

const outputPath = path.resolve(__dirname, "../src/data/worldDots.ts");
fs.writeFileSync(outputPath, outputContent, "utf-8");
console.log(`Successfully generated ${outputPath}`);
